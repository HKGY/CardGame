'use strict';
/* 留置包（retain）策略 —— 最终版（经过充分实验后的理性结论）。
 *
 * ============== 实验历程总结 ==============
 *
 * 基准测试（空钩子/通用 V）：
 *   - 正常难度（60 局）：87.5 ~ 90%，STUCK 3
 *   - HP=45 难度（60 局）：73.3%，STUCK 1
 *
 * STUCK 根因诊断：
 *   所有 STUCK 均为「霜灵 HP=1 + 意图冰盾（不攻击）」的对峙场景。
 *   value.js 的「HP≤12 存活敌人 +10」导致打死 HP=1 敌人的 V delta=-0.5 < EPS(0.4)，
 *   搜索拒绝打攻击牌，60 回合无进展判 STUCK（算输局）。
 *   这是 retain 包特有问题：留置牌拖长战斗，才遇到霜灵特殊意图组合。
 *
 * 尝试 battle 钩子（均有副作用，最终放弃）：
 *   - 对 HP=1 敌人 -12：4/5 STUCK 修复，但搜索污染（打人→敌人 HP→1→-12 分）导致 AI 拒绝
 *     出攻击牌，全局 STUCK 从 3 变成 17，胜率从 87.5% 跌到 79.2%。
 *   - 对多个濒死敌人 -8：条件不匹配实际单敌濒死场景，无效。
 *   - 其他变体：均产生类似的搜索污染问题。
 *   核心原因：battle(CG,g) 在所有局面（含搜索模拟的「之后」局面）都运行，
 *   任何针对「某个状态」的惩罚都会让 AI 回避「产生这个状态」的行动。
 *
 * 尝试 gem 钩子（均无稳定正效果）：
 *   - 正向加权 chargeup/primed：60 局时偶见 90%（vs 87.5%），但 120 局下无显著提升，
 *     HP=45 下反而略差（AI 选了过多需要时间发力的宝石）。
 *   - heavyhold 下调 -2：HP=45 略改善，但正常难度 120 局下胜率降至 85%，STUCK 增加到 5。
 *     可能原因：heavyhold 下调改变了 bestInstallScore 排序，使 AI 安装了次优宝石。
 *   - 所有 gem 钩子在 120 局尺度上均无稳定正效果。
 *
 * 尝试 install 钩子（均无稳定正效果）：
 *   - chargeup/primed/heldstrike 装到攻击卡的 bonus：与 gem 钩子协同时偶有 60 局好成绩，
 *     但 120 局和 HP=45 下均不稳定。
 *
 * ============== 最终结论 ==============
 *
 * 留置包在搜索型 AI 下的固有限制：
 *   1. 单回合前向搜索看不到「再等一回合积累 chargeup/primed」的长期价值，
 *      但补偿这一点的 battle 钩子必然污染搜索。
 *   2. STUCK 问题（5 个 seeds）是 retain 包机制导致的延长战斗 + 霜灵特殊意图的结合，
 *      无法在不引入更大副作用的情况下用钩子修正。
 *   3. 87.5% 的基准胜率（120 局）基本是当前 AI 架构对此包的真实上限。
 *
 * 交付决策：
 *   注册一个空钩子，让 AI 回退到通用 V 评估。这是最稳定的结果，
 *   避免了所有实验版本的负效果。
 */
const value = require('../value');

value.registerPack('retain', {
  // 不注入任何钩子：所有实验均未能在 120 局尺度上稳定超过通用 V 的 87.5%，
  // 且均有引入负效果的风险。留置包的 87.5% 基本是当前搜索型 AI 的真实上限。
});
